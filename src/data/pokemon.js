// matching how they actually work in the games. The dex number is used to fetch real
// artwork from PokeAPI's public sprite repo.

function formatDexId(id) {
  if (!id) return '';
  if (id > 9999) return `#${id}`;
  return `#${String(id).padStart(3, '0')}`;
}

